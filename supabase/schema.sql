create extension if not exists pgcrypto;

-- ---------- Enum types ----------------------------------------------
do $$ begin
  create type task_status   as enum ('todo','in_progress','done','planned','tentative');
  create type task_priority as enum ('critical','high','medium','low');
  create type task_owner    as enum ('bride','groom','couple','family','vendor');
  create type task_category as enum ('venue','indoor_shoot','outdoor_shoot','family','invitation',
                                     'guest_management','ceremony','honeymoon','budget','post_wedding');
  create type shoot_kind    as enum ('indoor','outdoor');
  create type member_role   as enum ('bride','groom','planner','viewer');
exception when duplicate_object then null; end $$;

-- ---------- Projects ------------------------------------------------
create table if not exists projects (
  id                    uuid primary key default gen_random_uuid(),
  name                  text not null,
  wedding_date          date not null,
  ceremony_time         time,
  venue                 text,
  timezone              text not null default 'Asia/Seoul',
  status                text not null default 'planning',
  estimated_guest_count integer check (estimated_guest_count >= 0),
  budget_target_krw     bigint  check (budget_target_krw >= 0),
  notes                 text[] not null default '{}',
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

-- 공동 편집자(신랑·신부). 이메일 기준으로 접근 권한을 부여한다.
create table if not exists project_members (
  project_id uuid not null references projects(id) on delete cascade,
  email      text not null,
  role       member_role not null default 'viewer',
  can_edit   boolean not null default true,
  created_at timestamptz not null default now(),
  primary key (project_id, email)
);

create table if not exists confirmed_items (
  id         bigint generated by default as identity primary key,
  project_id uuid not null references projects(id) on delete cascade,
  title      text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

-- ---------- Tasks ---------------------------------------------------
create table if not exists tasks (
  project_id         uuid not null references projects(id) on delete cascade,
  id                 text not null,                  -- e.g. WED-001
  title              text not null,
  category           task_category not null,
  start_date         date,
  due_date           date,                           -- null = 미정 (임의 확정 금지)
  status             task_status   not null default 'todo',
  priority           task_priority not null default 'medium',
  owner              task_owner    not null default 'couple',
  description        text,
  estimated_cost_krw bigint check (estimated_cost_krw >= 0),
  actual_cost_krw    bigint check (actual_cost_krw >= 0),
  vendor             text,
  booking_url        text,
  memo               text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  updated_by         text,
  primary key (project_id, id),
  check (start_date is null or due_date is null or start_date <= due_date)
);
create index if not exists tasks_due_idx on tasks (project_id, due_date);

create table if not exists task_dependencies (
  project_id    uuid not null,
  task_id       text not null,
  depends_on_id text not null,
  primary key (project_id, task_id, depends_on_id),
  foreign key (project_id, task_id)       references tasks(project_id, id) on delete cascade,
  foreign key (project_id, depends_on_id) references tasks(project_id, id) on delete cascade,
  check (task_id <> depends_on_id)
);

-- ---------- Shoots --------------------------------------------------
create table if not exists shoots (
  project_id               uuid not null references projects(id) on delete cascade,
  kind                     shoot_kind not null,
  vendor                   text,
  vendor_selected          boolean not null default false,
  photographer             text,
  vendor_booking_required  boolean not null default true,
  shoot_date               date,
  shoot_date_status        text not null default 'undecided',  -- undecided | tentative | confirmed
  outfit_source            text,
  target_completion_date   date,
  edited_photo_target_date date,
  window_start             date,
  window_end               date,
  location_mood            text,
  location                 text,
  backup_date              date,                               -- 날씨 대체일
  notes                    text[] not null default '{}',
  updated_at               timestamptz not null default now(),
  primary key (project_id, kind),
  check (window_start is null or window_end is null or window_start <= window_end)
);

-- 촬영일 기준 상대 마감일 규칙 (6주 전 콘셉트, 4주 전 의상 ...)
create table if not exists relative_deadline_rules (
  project_id  uuid not null references projects(id) on delete cascade,
  key         text not null,
  label       text not null,
  anchor      text not null default 'indoor_shoot',
  offset_days integer not null,
  task_id     text,
  primary key (project_id, key),
  foreign key (project_id, task_id) references tasks(project_id, id) on delete set null
);

-- 반복 작업 규칙 (단발 작업과 분리). rrule 은 RFC 5545 형식 문자열.
create table if not exists recurring_rules (
  id         bigint generated by default as identity primary key,
  project_id uuid not null references projects(id) on delete cascade,
  title      text not null,
  category   task_category not null,
  owner      task_owner not null default 'couple',
  rrule      text not null,             -- e.g. 'FREQ=WEEKLY;BYDAY=SU'
  start_date date not null,
  end_date   date,
  active     boolean not null default true,
  memo       text,
  created_at timestamptz not null default now()
);

-- ---------- Honeymoon -----------------------------------------------
create table if not exists honeymoon (
  project_id             uuid primary key references projects(id) on delete cascade,
  route_idea             text[] not null default '{}',
  duration_idea          text,
  preferred_period       text,
  departure_constraint   text,
  prior_commitment       text,
  prior_commitment_start date,
  prior_commitment_end   date,
  booking_status         text not null default 'not_booked',
  updated_at             timestamptz not null default now()
);

-- ---------- updated_at triggers ------------------------------------
create or replace function touch_updated_at() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['projects','tasks','shoots','honeymoon'] loop
    execute format('drop trigger if exists trg_touch_%1$s on %1$s', t);
    execute format('create trigger trg_touch_%1$s before update on %1$s
                    for each row execute function touch_updated_at()', t);
  end loop;
end $$;

-- ---------- 촬영일 확정 시 상대 마감일 자동 계산 -------------------
create or replace function apply_relative_deadlines() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.kind = 'indoor' and new.shoot_date is not null
     and new.shoot_date is distinct from old.shoot_date then
    update tasks t
       set due_date = new.shoot_date + r.offset_days
      from relative_deadline_rules r
     where r.project_id = new.project_id
       and r.anchor = 'indoor_shoot'
       and t.project_id = r.project_id
       and t.id = r.task_id
       and t.status <> 'done';
  end if;
  return new;
end $$;

drop trigger if exists trg_relative_deadlines on shoots;
create trigger trg_relative_deadlines after update of shoot_date on shoots
  for each row execute function apply_relative_deadlines();

-- ---------- Views ---------------------------------------------------
-- 선행 작업이 끝나지 않아 막혀 있는 작업
create or replace view v_task_blockers with (security_invoker = true) as
select d.project_id, d.task_id, d.depends_on_id, p.status as depends_on_status
  from task_dependencies d
  join tasks p on p.project_id = d.project_id and p.id = d.depends_on_id
 where p.status <> 'done';

-- 예산 요약
create or replace view v_budget_summary with (security_invoker = true) as
select pr.id as project_id,
       pr.budget_target_krw,
       coalesce(sum(t.estimated_cost_krw), 0) as estimated_total_krw,
       coalesce(sum(t.actual_cost_krw), 0)    as actual_total_krw
  from projects pr
  left join tasks t on t.project_id = pr.id
 group by pr.id, pr.budget_target_krw;

-- ---------- Row Level Security: 로그인 없이 공개 편집 ----------------
-- 누구나(anon 포함) 조회·추가·수정·삭제할 수 있습니다. 사이트 주소를 아는 사람은 모두 편집 가능.
-- project_members 는 사용하지 않으며 공개하지 않습니다(정책 없음 = 접근 불가).
do $$
declare t text;
begin
  foreach t in array array['projects','project_members','confirmed_items','tasks','task_dependencies',
                           'shoots','relative_deadline_rules','recurring_rules','honeymoon'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists %1$s_read  on %1$I', t);
    execute format('drop policy if exists %1$s_write on %1$I', t);
    execute format('drop policy if exists %1$s_public on %1$I', t);
    if t <> 'project_members' then
      execute format('create policy %1$s_public on %1$I for all to anon, authenticated using (true) with check (true)', t);
    end if;
  end loop;
end $$;

-- ---------- Realtime ------------------------------------------------
